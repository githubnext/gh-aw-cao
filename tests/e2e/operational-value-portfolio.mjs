import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { readCensusJson } from "../../scripts/operational-value-census-io.mjs";
import { portfolioTableModel } from "../../scripts/workflow-portfolio-table.mjs";

test("populated standalone coverage report sorts, selects statuses and remains usable on mobile", async t => {
  const root = new URL("../../docs/operational-value/gh-aw-workflows/", import.meta.url);
  const manifest = readCensusJson(fileURLToPath(new URL("portfolio.json.gz", root)));
  const workflows = manifest.partitions.flatMap(part => readCensusJson(fileURLToPath(new URL(part.file, root))));
  const model = portfolioTableModel(workflows);
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto(new URL("index.html", root).href);
  assert.equal(await page.locator("tbody > tr").count(), manifest.totals.workflows);
  const visibleNames = () => page.locator("tbody > tr:visible th[scope=row] > a").allTextContents();
  const names = order => order.map(index => workflows[index].id);
  assert.deepEqual(await visibleNames(), names(model.orders.signal));
  await page.getByRole("combobox", { name: "Sort" }).selectOption("coverage");
  assert.deepEqual(await visibleNames(), names(model.orders.coverage));
  const coverage = page.getByRole("button", { name: /Evaluation coverage/ });
  await coverage.focus();
  await coverage.press("Enter");
  assert.equal(await page.locator('th[data-sort="coverage"]').getAttribute("aria-sort"), "descending");
  assert.deepEqual(await visibleNames(), names(model.orders.coverage.toReversed()));
  assert.ok(await coverage.evaluate(element => element === element.ownerDocument.activeElement));
  await coverage.press("Enter");
  assert.deepEqual(await visibleNames(), names(model.orders.coverage));
  for (const id of ["native", "stale", "improving", "gaps", "not-evaluated", "review"]) {
    await page.getByRole("combobox", { name: "Show" }).selectOption(id);
    const group = model.groups.find(group => group.id === id);
    const selected = new Set(group.rows);
    assert.deepEqual(await visibleNames(), names(model.orders.coverage.filter(index => selected.has(index))));
    assert.equal(await page.getByRole("status").textContent(), `${group.rows.length} of ${workflows.length} workflows shown`);
    assert.equal(await page.locator("[data-empty]").isVisible(), group.rows.length === 0);
  }
  await page.getByRole("combobox", { name: "Show" }).selectOption("all");
  await page.getByRole("combobox", { name: "Sort" }).selectOption("freshness");
  assert.deepEqual(await visibleNames(), names(model.orders.freshness));
  await page.getByRole("combobox", { name: "Sort" }).selectOption("signal");
  const artifacts = process.env.CAO_REPORT_ARTIFACT_DIR ?? fileURLToPath(new URL("../../test-results/operational-value-portfolio/", import.meta.url));
  mkdirSync(artifacts, { recursive: true });
  await page.screenshot({ path: path.join(artifacts, "coverage-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator(".coverage-scroll").evaluate(element => element.scrollWidth > element.clientWidth));
  await page.getByRole("combobox", { name: "Sort" }).selectOption("coverage");
  assert.deepEqual(await visibleNames(), names(model.orders.coverage));
  await page.screenshot({ path: path.join(artifacts, "coverage-mobile.png"), fullPage: true });
  await page.emulateMedia({ colorScheme: "dark" });
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(13, 17, 23)");
  const firstLink = page.locator("tbody > tr:visible th[scope=row] > a").first();
  const target = await firstLink.getAttribute("href");
  await firstLink.click();
  assert.ok(page.url().endsWith(target));
  assert.equal(await page.locator(page.url().slice(page.url().indexOf("#"))).count(), 1);
  assert.deepEqual(errors, []);
});
