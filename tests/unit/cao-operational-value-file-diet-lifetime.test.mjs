const inventory = (commit, rows) => {
  const files = rows.map(([path, lines]) => ({ path, lines }));
  return { commit, files, inventoryDigest: censusDigest(files) };
};
const example = () => ({
  proof: {
    adoption: { at: "2025-11-15T13:36:21Z" }, until: "2026-01-01T00:00:00Z",
    snapshots: [{ at: "2025-11-15T13:36:21Z", commit: "before" }, { at: "2026-01-01T00:00:00Z", commit: "after" }],
    issues: [{ id: "I_1", number: 1, targetPath: "pkg/workflow/large.go", createdAt: "2025-11-16T13:00:00Z",
      timeline: { complete: true, events: [] } }],
    pulls: [{ id: "PR_2", number: 2, createdAt: "2025-11-17T00:00:00Z", mergedAt: "2025-12-01T00:00:00Z",
      creatorRole: "copilot", preMergeSha: "before", mergeSha: "after",
      files: [{ status: "added", path: "pkg/workflow/split.go" }],
      graph: { closingLinksComplete: true, edges: [{ relation: "declares-closing", target: { id: "I_1" } }] } }],
  },
  inventories: {
    before: inventory("before", [["pkg/workflow/large.go", 1200]]),
    after: inventory("after", [["pkg/workflow/large.go", 450], ["pkg/workflow/split.go", 450]]),
  },
});

test("historical named footers recognize the verified repository rename without accepting conflicting runs", () => {
  const old = "AI generated by [Daily File Diet](https://github.com/githubnext/gh-aw/actions/runs/123)";
  assert.equal(originReference(old).runId, "123");
  assert.equal(originReference("<!-- agentic-workflow: Daily File Diet, run: https://github.com/github/gh-aw/actions/runs/123 -->").runId, "123");
  assert.equal(originReference("A casual Daily File Diet mention"), null);
  assert.throws(() => originReference(`${old}\n${old.replace("/123", "/456")}`), /Conflicting/);
  assert.throws(() => originReference(old.replace("githubnext/gh-aw", "someone/else")), /Unrecognized/);
});

test("historical alias admission requires identical immutable repository identities", () => {
  assert.throws(() => acquireHistory(endpoint => endpoint === "repos/github/gh-aw"
    ? { id: 1, full_name: "github/gh-aw" } : { id: 2, full_name: "github/gh-aw" }), /different repository/);
});

test("threshold changes and contradictory transition contracts remain explicit", () => {
  assert.equal(thresholdContract("Files over 1,000 lines").threshold, 1000);
  assert.equal(thresholdContract("Healthy file size threshold: 800 lines").threshold, 800);
  const ambiguous = thresholdContract("Healthy threshold: 800 lines\nCreate an issue for files >= 1000 lines");
  assert.equal(ambiguous.threshold, null);
  assert.deepEqual(ambiguous.thresholds, [800, 1000]);
});

test("calendar periods cover adoption through the final partial month without gaps", () => {
  assert.deepEqual(monthlyCutoffs("2025-11-15T13:36:21Z", "2026-02-10T12:00:00Z"), [
    "2025-11-15T13:36:21Z", "2025-12-01T00:00:00Z", "2026-01-01T00:00:00Z",
    "2026-02-01T00:00:00Z", "2026-02-10T12:00:00Z",
  ]);
});

test("linked merged structural changes are separate from unknown behavior-preserving acceptance", () => {
  const { proof, inventories } = example();
  const result = evaluateLifetime(proof, inventories);
  assert.deepEqual(result.periods.map(item => item.oversized800), [1, 0]);
  assert.equal(result.deliveries[0].targets[0].resolved800, true);
  assert.equal(result.deliveries[0].targets[0].newFilesUnder500, true);
  assert.equal(result.totals.mergedExplicitlyLinkedPulls, 1);
  assert.equal(result.totals.acceptedBehaviorPreserving, null);
  assert.equal(result.periods[1].acceptedBehaviorPreserving, null);
});

test("incidental cross-references and disconnected handoffs do not become explicit delivery links", () => {
  const { proof, inventories } = example();
  proof.pulls[0].graph.edges[0].relation = "referenced-by";
  proof.issues[0].timeline.events = ["connected", "disconnected"].map((type, index) => ({
    type, at: `2025-11-${18 + index}T00:00:00Z`, target: { kind: "pull-request", number: 2 },
  }));
  assert.equal(evaluateLifetime(proof, inventories).totals.mergedExplicitlyLinkedPulls, 0);
  proof.issues[0].timeline.events.pop();
  assert.equal(evaluateLifetime(proof, inventories).totals.mergedExplicitlyLinkedPulls, 1);
});

test("missing creation receipts qualify attribution without erasing independently verified structural delivery", () => {
  const { proof, inventories } = example();
  proof.issues[0].receipt = { status: "missing" };
  const result = evaluateLifetime(proof, inventories);
  assert.equal(result.totals.linkedNetOversized800Reduction, 1);
  assert.equal(result.totals.receiptLinkedResolved800, 0);
  assert.equal(result.totals.acceptedBehaviorPreserving, null);
});

test("a surviving improvement earns delivery credit only once and duplicate target reports are deduplicated", () => {
  const { proof, inventories } = example();
  proof.issues.push({ ...proof.issues[0], number: 3, id: "I_3" });
  proof.pulls[0].graph.edges.push({ relation: "declares-closing", target: { id: "I_3" } });
  proof.snapshots.push({ at: "2026-02-01T00:00:00Z", commit: "after" });
  proof.until = "2026-02-01T00:00:00Z";
  const result = evaluateLifetime(proof, inventories);
  assert.equal(result.totals.resolved800, 1);
  assert.deepEqual(result.periods.map(item => item.resolved800.length), [0, 1, 0]);
});

test("corrupt or absent inventories fail closed instead of becoming zero", () => {
  const { proof, inventories } = example();
  inventories.before.files[0].lines = 799;
  assert.throws(() => evaluateLifetime(proof, inventories), /corrupt inventory/);
  delete inventories.before;
  assert.throws(() => evaluateLifetime(proof, inventories), /corrupt inventory/);
});

test("legacy composite identities and newer node IDs both require exact safe-output receipt matches", () => {
  const content = JSON.stringify({ type: "create_issue", number: 1, repo: "github/gh-aw",
    url: "https://github.com/github/gh-aw/issues/1" });
  const issue = { number: 1, id: "I_1", reference: { runId: "123" }, run: { validation: { headSha: "abc" } },
    receipt: { status: "available", runId: 123, headSha: "abc", content,
      entrySha256: createHash("sha256").update(content).digest("hex"), archiveSha256: "abc", digest: "sha256:abc" } };
  assert.equal(verifyCreationReceipt(issue), true);
  issue.receipt.content = JSON.stringify({ ...JSON.parse(content), metadata: { node_id: "WRONG" } });
  issue.receipt.entrySha256 = createHash("sha256").update(issue.receipt.content).digest("hex");
  assert.throws(() => verifyCreationReceipt(issue), /WRONG/);
  assert.equal(verifyCreationReceipt({ receipt: { status: "missing" } }), false);
});

test("renaming a large file does not imply a native reduction and 500-line replacements fail the size safeguard", () => {
  const { proof, inventories } = example();
  proof.pulls[0].files = [{ status: "renamed", path: "pkg/workflow/renamed.go" }];
  inventories.after = inventory("after", [["pkg/workflow/renamed.go", 1200]]);
  let result = evaluateLifetime(proof, inventories);
  assert.equal(result.deliveries[0].targets[0].resolved800, true);
  assert.equal(result.deliveries[0].oversized800Reduction, 0);
  assert.equal(result.deliveries[0].targets[0].newFilesUnder500, false);
  inventories.after = inventory("after", [["pkg/workflow/renamed.go", 500]]);
  result = evaluateLifetime(proof, inventories);
  assert.equal(result.deliveries[0].targets[0].newFilesUnder500, false);
});

test("retained-run pagination exposes known deleted runs without claiming a complete execution denominator", () => {
  const proof = { repositoryId: 1, issues: [{ reference: { runId: "999" } }],
    snapshots: [{ at: "2025-11-15T13:36:21Z" }, { at: "2025-12-01T00:00:00Z" }] };
  const runs = Array.from({ length: 101 }, (_, index) => ({ id: index + 1, created_at: "2025-11-16T00:00:00Z",
    path: ".github/workflows/daily-file-diet.lock.yml", repository: { id: 1 }, conclusion: "success" }));
  const request = endpoint => ({ total_count: 101,
    workflow_runs: endpoint.endsWith("page=1") ? runs.slice(0, 100) : runs.slice(100) });
  const result = acquireExecutions(proof, request);
  assert.equal(result.runs.length, 101);
  assert.deepEqual(result.missingReferencedRunIds, ["999"]);
  assert.equal(result.completeHistoricalExecutions, false);
  assert.throws(() => acquireExecutions(proof, () => ({ total_count: 1000 })), /result cap/);
});

