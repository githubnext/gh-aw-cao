import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, test } from "node:test";
import { eligibleFunctionLengthPath, scanNativeFunctionLengths, scoreNativeFunctionLength } from "../../scripts/native-function-length-value.mjs";
import { readCensusJson } from "../../scripts/operational-value-census-io.mjs";

const temporary = mkdtempSync(path.join(os.tmpdir(), "cao-function-length-"));
after(() => rmSync(temporary, { recursive: true, force: true }));
const binary = path.join(temporary, "oracle");
execFileSync("go", ["build", "-o", binary, "scripts/operational-value-function-length-oracle.go"], { timeout: 120000 });
const measure = content => {
  const id = createHash("sha1").update(`blob ${Buffer.byteLength(content)}\0`).update(content).digest("hex");
  return JSON.parse(execFileSync(binary, [], { encoding: "utf8", input: JSON.stringify({ id, content }) + "\n", timeout: 30000 }));
};
const evidence = feature => ({ valid: true, complete: true, files: [{ path: "pkg/example/example.go", feature }] });
const source = (lines, comment = "") => `package example\n${comment}func example() {\n${"\tprintln(1)\n".repeat(lines)}}\n`;

test("native brace-line predicate preserves the exact 60/61 boundary", () => {
  assert.equal(scoreNativeFunctionLength("overlong-bodies", evidence(measure(source(60)))), 0);
  const fact = measure(source(61));
  assert.equal(fact.functions[0].bodyLines, 61);
  assert.equal(scoreNativeFunctionLength("overlong-bodies", evidence(fact)), 1);
  assert.equal(fact.contentSha256, createHash("sha256").update(source(61)).digest("hex"));
});

test("suppression is diagnostic metadata, never a raw structural repair", () => {
  for (const directive of ["//nolint:largefunc\n", "// nolint:all // explanation\n", "//nolint:other,largefunc\n"]) {
    const scan = scanNativeFunctionLengths(evidence(measure(source(61, directive))));
    assert.equal(scan["overlong-bodies"], 1);
    assert.equal(scan["unsuppressed-bodies"], 0);
    assert.equal(scan["suppressed-bodies"], 1);
  }
  for (const directive of ["//nolint:other\n", "/*nolint:largefunc*/\n", "//nolint:largefunc-extra\n", "//nolint:all\n\n"]) {
    assert.equal(scoreNativeFunctionLength("unsuppressed-bodies", evidence(measure(source(61, directive)))), 1);
  }
});

test("native declarations, nested literals, inline functions and methods stay distinct", () => {
  const fact = measure("package example\nfunc outer() {\n f := func() {\n println(1)\n }\n _ = f\n}\nfunc inline() {}\ntype T struct{}\nfunc (T) method() {}\nfunc assembly()\n");
  assert.deepEqual(fact.functions.map(fn => [fn.kind, fn.bodyLines]),
    [["declaration", 4], ["literal", 1], ["declaration", -1], ["declaration", -1]]);
});

test("generated sources are excluded and unavailable syntax/directives stay unknown", () => {
  assert.equal(scanNativeFunctionLengths(evidence(measure("// Code generated by example. DO NOT EDIT.\n" + source(61))))["overlong-bodies"], 0);
  assert.equal(scanNativeFunctionLengths(evidence(measure("package example\nfunc broken( {\n"))), null);
  assert.equal(scanNativeFunctionLengths(evidence(measure("package example\n//line other.go:100\nfunc example() {}\n"))), null);
  assert.equal(measure('package example\nvar example = "//line other.go:100"\n').hasLineDirectives, false);
});

test("scope and malformed evidence fail closed without counting test or ignored trees", () => {
  for (const file of ["pkg/a/a_test.go", "pkg/testdata/a.go", "cmd/.hidden/a.go", "pkg/_ignored/a.go", "vendor/pkg/a.go"]) {
    assert.equal(eligibleFunctionLengthPath(file), false);
  }
  for (const file of ["cmd/linters/main.go", "pkg/a/a_linux.go", "pkg/a/a_windows.go"]) {
    assert.equal(eligibleFunctionLengthPath(file), true);
  }
  const input = evidence(measure(source(61)));
  assert.equal(scanNativeFunctionLengths({ ...input, complete: false }), null);
  assert.equal(scanNativeFunctionLengths({ ...input, files: [] }), null);
  assert.equal(scanNativeFunctionLengths({ ...input, files: [...input.files, ...input.files] }), null);
  assert.equal(scanNativeFunctionLengths(evidence({ ...input.files[0].feature, functions: [{ line: 1, bodyLines: "61" }] })), null);
  assert.throws(() => scoreNativeFunctionLength("opened-prs", input), /Unknown/);
  assert.throws(() => execFileSync(binary, [], { input: JSON.stringify({ id: "a".repeat(40), content: source(61) }) + "\n",
    stdio: ["pipe", "pipe", "pipe"] }), /immutable Go blob identity mismatch/);
});

test("retained lifetime source replay distinguishes real structural movement from suppressions", async () => {
  const directory = "docs/operational-value/proof/function-length";
  const [contract] = readCensusJson(`${directory}/contracts.json`);
  const { definition, collectBatch } = await import("../../docs/operational-value/proof/functions/lint-monster.mjs");
  const facts = readCensusJson(`${directory}/facts.json.gz`);
  const rows = collectBatch(facts.states.map(state => ({ windowEnd: state.windowEnd })));
  assert.equal(rows.length, 24);
  assert.ok(rows.every(row => row.evidence.coverageStatus === "complete"));
  assert.equal(scoreNativeFunctionLength("overlong-bodies", rows[0].evidence), 672);
  assert.equal(scoreNativeFunctionLength("overlong-bodies", rows.at(-1).evidence), 539);
  assert.equal(scoreNativeFunctionLength("unsuppressed-bodies", rows.at(-1).evidence), 404);
  assert.equal(scoreNativeFunctionLength("suppressed-bodies", rows.at(-1).evidence), 135);
  assert.equal(rows.at(-1).evidence.eligibleCount, 12608);
  assert.equal(rows.at(-1).evidence.fullGoalAcceptance, "not-measured");
  assert.equal(rows.at(-1).evidence.workflowCausation, "not-measured");
  const index = readCensusJson(`${directory}/index.json`);
  assert.equal(index.sourceBlobs, 6632);
  assert.equal(contract.oracleSha256, createHash("sha256")
    .update(readFileSync("scripts/operational-value-function-length-oracle.go")).digest("hex"));
  assert.equal(definition.evidence.measurementKind, "snapshot");
});
