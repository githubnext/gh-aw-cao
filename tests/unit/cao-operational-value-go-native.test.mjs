import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { parseGitChanges } from "../../.github/skills/add-operational-value/scripts/git-evidence.mjs";
import { evaluateGoHistory, goFormattingEffect, goParallelEffect } from "../../scripts/native-go-measures.mjs";
import { goParallelizationValueEvents } from "../../scripts/build-go-parallelization-value-events.mjs";
import { readGoHistory } from "../../scripts/measure-go-native-history.mjs";
import { collectBatch, definition, scoreMetric } from "../../docs/operational-value/proof/functions/daily-go-test-parallelizer.mjs";

const directory = mkdtempSync(path.join(os.tmpdir(), "native-go-value-"));
const binary = path.join(directory, "oracle");
test.after(() => rmSync(directory, { recursive: true, force: true }));
execFileSync("go", ["build", "-o", binary, "scripts/operational-value-go-oracle.go"], { timeout: 120000 });
const facts = contents => execFileSync(binary, [], { encoding: "utf8",
  input: contents.map((content, i) => JSON.stringify({ id: String(i), content })).join("\n") + "\n",
}).trim().split("\n").map(line => JSON.parse(line));
const source = body => `package p\nimport "testing"\nfunc TestUseful(t *testing.T) { ${body} }\n`;

test("the oracle proves an isolated leading parallel call without trusting comments or strings", () => {
  const [before, after, comment, nested, changed, unsafe] = facts([
    source('t.Log("hello")'), source('t.Parallel(); t.Log("hello")'),
    source('// t.Parallel()\nt.Log("hello")'), source('if true { t.Parallel() }; t.Log("hello")'),
    source('t.Parallel(); t.Log("different behavior")'),
    source('t.Parallel(); t.Setenv("KEY","VALUE"); t.Log("hello")'),
  ]);
  assert.equal(before.tests[0].bodySha256, after.tests[0].bodySha256);
  assert.equal(goParallelEffect(before, after).value, 1);
  assert.equal(goParallelEffect(after, before).value, -1);
  assert.equal(goParallelEffect(before, comment).value, 0);
  assert.equal(goParallelEffect(before, nested).value, 0);
  assert.equal(goParallelEffect(before, changed).value, 0);
  assert.equal(unsafe.tests[0].processStateCalls, 1);
  assert.equal(goParallelEffect(before, unsafe).value, 0);
  const [empty, parallelOnly] = facts([source(""), source("t.Parallel()")]);
  assert.equal(empty.tests[0].bodySha256, parallelOnly.tests[0].bodySha256);
  assert.equal(goParallelEffect(empty, parallelOnly).value, 1);
});

test("scope resolution handles import aliases and does not confuse another receiver with the test parameter", () => {
  const [alias, wrong, global, blank, generated, invalid] = facts([
    'package p\nimport check "testing"\nfunc TestUseful(tt *check.T) { tt.Parallel() }\n',
    source('other.Parallel(); t.Log("t.Parallel()")'),
    'package p\nimport "testing"\nvar shared int\nfunc TestUseful(t *testing.T) { t.Parallel(); shared++ }\n',
    'package p\nimport "testing"\nfunc TestUseful(_ *testing.T) { other.Parallel() }\n',
    '// Code generated by tool. DO NOT EDIT.\n' + source('t.Parallel()'),
    'package p\nfunc broken(',
  ]);
  assert.equal(alias.tests[0].leadingParallel, true);
  assert.equal(wrong.tests[0].leadingParallel, false);
  assert.ok(global.tests[0].globalReferences > 0);
  assert.equal(blank.tests[0].leadingParallel, false);
  assert.equal(goParallelEffect(alias, generated).status, "generated-excluded");
  assert.equal(goParallelEffect(alias, invalid).value, null);
});

test("formatting credit requires exact canonical output, not an arbitrary edit or deleted file", () => {
  const raw = source('t.Log("hello")');
  const canonical = execFileSync("gofmt", [], { input: raw, encoding: "utf8" });
  const [before, after, changed] = facts([raw, canonical, source('t.Log("different")')]);
  assert.equal(goFormattingEffect(before, after).value, 1);
  assert.equal(goFormattingEffect(after, before).value, -1);
  assert.equal(goFormattingEffect(before, changed).value, 0);
  assert.equal(goFormattingEffect(before, null).value, 0);
});

test("raw immutable Git history retains exact before/after blob identities and complete source paths", () => {
  const git = (...args) => execFileSync("git", ["-C", directory, ...args], { encoding: "utf8" });
  git("init", "--quiet"); git("config", "user.name", "Fixture"); git("config", "user.email", "fixture@example.invalid");
  writeFileSync(path.join(directory, "example_test.go"), source('t.Log("hello")'));
  git("add", "example_test.go"); git("commit", "--quiet", "-m", "Initial");
  const baseline = git("rev-parse", "HEAD").trim();
  writeFileSync(path.join(directory, "example_test.go"), source('t.Parallel(); t.Log("hello")'));
  git("add", "example_test.go"); git("commit", "--quiet", "-m", "Parallelize");
  const parsed = parseGitChanges(Buffer.from(git("log", "--first-parent", "--raw", "--no-abbrev",
    "--no-renames", "--diff-merges=first-parent", "--format=%x00VALUE-COMMIT%x00%H%x00%P%x00%cI%x00",
    "-z", "HEAD", `^${baseline}`, "--", "*.go")));
  assert.equal(parsed.length, 1);
  assert.equal(parsed[0].changes[0].path, "example_test.go");
  const change = parsed[0].changes[0];
  const features = facts([git("show", `${baseline}:example_test.go`), git("show", "HEAD:example_test.go")]);
  features[0].id = change.beforeBlob; features[1].id = change.afterBlob;
  assert.equal(evaluateGoHistory(parsed, features)[0].parallel, 1);
  assert.throws(() => evaluateGoHistory(parsed, features.slice(1)), /Missing immutable/);
});

test("the published Go series replays from preserved native blobs, graph links and its actual value function", () => {
  const native = readGoHistory("docs/operational-value/proof/go-parallelization/native-v2");
  assert.equal(native.index.oracleSha256, definition.evidence.oracleSha256);
  const events = goParallelizationValueEvents();
  const [{ evidence }] = collectBatch([{ repository: definition.repository,
    windowStart: events.window.startAt, windowEnd: events.window.endAt, observedAt: events.observedAt }]);
  assert.equal(scoreMetric("native-net", evidence), native.evaluated.reduce((sum, row) => sum + row.parallel, 0));
  assert.equal(scoreMetric("corroborated-net", evidence), events.events.reduce((sum, row) => sum + row.value, 0));
  assert.deepEqual(events, JSON.parse(readFileSync(
    "docs/operational-value/proof/reports/go-parallelization-value-events.json", "utf8")));
});
