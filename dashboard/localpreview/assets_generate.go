//go:build ignore

// Regenerate the browser-only archive after changing dashboard/site's locked
// dependencies. This development command uses native esbuild, never Node.
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/base64"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	executable := flag.String("esbuild", "", "path to the native esbuild binary")
	modules := flag.String("modules", "", "additional directory containing locked browser packages")
	flag.Parse()
	root, err := filepath.Abs("../..")
	if err != nil {
		return err
	}
	if *executable == "" {
		*executable = os.Getenv("ESBUILD_BINARY_PATH")
	}
	if *executable == "" {
		*executable = filepath.Join(root, "node_modules", "@esbuild", runtime.GOOS+"-"+runtime.GOARCH, "bin", "esbuild")
		if runtime.GOOS == "windows" {
			*executable += ".exe"
		}
	}
	roots := []string{*modules, filepath.Join(root, "dashboard", "site", "node_modules"), filepath.Join(root, "node_modules")}
	locate := func(name string) (string, error) {
		for _, directory := range roots {
			if directory == "" {
				continue
			}
			candidate := filepath.Join(directory, filepath.FromSlash(name))
			if info, err := os.Stat(candidate); err == nil && info.IsDir() {
				return filepath.Abs(candidate)
			}
		}
		return "", fmt.Errorf("missing locked browser package %s; restore dashboard/site dependencies before regenerating assets", name)
	}
	entries := []struct{ name, module, version, entry, symbol, license string }{
		{"yaml", "yaml", "2.9.0", "browser/index.js", "parseAllDocuments", "LICENSE"},
		{"xterm", "@xterm/xterm", "5.5.0", "lib/xterm.js", "Terminal", "LICENSE"},
		{"addon-fit", "@xterm/addon-fit", "0.10.0", "lib/addon-fit.js", "FitAddon", "LICENSE"},
		{"addon-web-links", "@xterm/addon-web-links", "0.11.0", "lib/addon-web-links.js", "WebLinksAddon", "LICENSE"},
		{"strip-ansi", "strip-ansi", "7.2.0", "index.js", "default", "license"},
	}
	assets := map[string]string{}
	var notices []string
	for _, entry := range entries {
		directory, err := locate(entry.module)
		if err != nil {
			return err
		}
		metadata, err := os.ReadFile(filepath.Join(directory, "package.json"))
		if err != nil {
			return err
		}
		var packageJSON struct{ Version string }
		if err := json.Unmarshal(metadata, &packageJSON); err != nil {
			return err
		}
		if packageJSON.Version != entry.version {
			return fmt.Errorf("%s version %s does not match the embedded browser contract %s", entry.module, packageJSON.Version, entry.version)
		}
		license, err := os.ReadFile(filepath.Join(directory, entry.license))
		if err != nil {
			return err
		}
		notices = append(notices, string(license))
		source := strconv.Quote(filepath.Join(directory, filepath.FromSlash(entry.entry)))
		input := "import {" + entry.symbol + "} from " + source + "; export {" + entry.symbol + "};"
		if entry.symbol == "default" {
			input = "import dep from " + source + "; export default dep;"
		}
		command := exec.Command(*executable, "--bundle", "--platform=browser", "--format=esm", "--target=es2022", "--minify", "--legal-comments=eof", "--log-level=error")
		command.Stdin = strings.NewReader(input)
		command.Stderr = os.Stderr
		content, err := command.Output()
		if err != nil {
			return err
		}
		assets["src/vendor/"+entry.name+".js"] = "/*\n" + string(license) + "\n*/\n" + string(content)
		if entry.name == "xterm" {
			css, err := os.ReadFile(filepath.Join(directory, "css", "xterm.css"))
			if err != nil {
				return err
			}
			content, _ := json.Marshal(string(css))
			assets["src/vendor/xterm-css.js"] = "/*\n" + string(license) + "\n*/\nexport default " + string(content) + ";\n"
		}
	}
	ansiRegex, err := locate("ansi-regex")
	if err != nil {
		return err
	}
	license, err := os.ReadFile(filepath.Join(ansiRegex, "license"))
	if err != nil {
		return err
	}
	notices = append(notices, string(license))
	assets["src/vendor/third-party-licenses.txt"] = strings.Join(notices, "\n\n")
	content, err := json.Marshal(assets)
	if err != nil {
		return err
	}
	var compressed bytes.Buffer
	archive := gzip.NewWriter(&compressed)
	if _, err := archive.Write(content); err != nil {
		return err
	}
	if err := archive.Close(); err != nil {
		return err
	}
	source := "// Code generated by go generate; DO NOT EDIT.\n// Locked browser-only dependencies; licenses are retained in the payload.\npackage localpreview\n\nconst browserAssetArchive = `" + base64.StdEncoding.EncodeToString(compressed.Bytes()) + "`\n"
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return err
	}
	return os.WriteFile("assets_generated.go", formatted, 0o644)
}
