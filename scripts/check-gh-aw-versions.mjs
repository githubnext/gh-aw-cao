import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const VERSION_PATTERN = /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
const POLICY_PATH = ".github/workflows/cao.json";
const WORKFLOW_DIRECTORY = ".github/workflows/";
const LOCK_SUFFIX = ".lock.yml";

function repositoryFiles(root) {
  try {
    return execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
      cwd: root,
      encoding: "utf8",
    })
      .split("\0")
      .filter(Boolean)
      .map((file) => file.replaceAll(path.sep, "/"));
  } catch {
    throw new Error("Unable to list repository files. Ensure Git is installed and this command runs inside the repository.");
  }
}

function read(root, relativePath) {
  return readFileSync(path.join(root, relativePath), "utf8");
}

function readCanonicalVersion(root) {
  let policy;
  try {
    policy = JSON.parse(read(root, POLICY_PATH));
  } catch (error) {
    throw new Error(`Unable to parse ${POLICY_PATH}: ${error.message}`);
  }

  const version = policy["gh-aw-version"];
  if (typeof version !== "string" || !VERSION_PATTERN.test(version)) {
    throw new Error(`${POLICY_PATH} gh-aw-version must be a v-prefixed semantic version`);
  }
  return version;
}

function checkManifest(root, relativePath, expectedVersion) {
  const source = read(root, relativePath);
  const match = /^min-version:\s*(?:"([^"]+)"|'([^']+)'|(\S+))\s*(?:#.*)?$/m.exec(source);
  const actualVersion = match?.[1] ?? match?.[2] ?? match?.[3];
  if (actualVersion !== expectedVersion) {
    return [`${relativePath}: min-version is ${JSON.stringify(actualVersion)}, expected ${expectedVersion}`];
  }
  return [];
}

function checkLock(root, relativePath, expectedVersion) {
  const source = read(root, relativePath);
  const metadataLine = source.split(/\r?\n/, 1)[0];
  const metadataPrefix = "# gh-aw-metadata: ";
  const issues = [];

  if (!metadataLine.startsWith(metadataPrefix)) {
    issues.push(`${relativePath}: missing gh-aw metadata header`);
  } else {
    try {
      const metadata = JSON.parse(metadataLine.slice(metadataPrefix.length));
      if (metadata.compiler_version !== expectedVersion) {
        issues.push(
          `${relativePath}: compiler_version is ${JSON.stringify(metadata.compiler_version)}, expected ${expectedVersion}`,
        );
      }
    } catch (error) {
      issues.push(`${relativePath}: invalid gh-aw metadata header: ${error.message}`);
    }
  }

  const generatedVersion = /automatically generated by gh-aw \((v[^)]+)\)/.exec(source)?.[1];
  if (generatedVersion !== expectedVersion) {
    issues.push(
      `${relativePath}: generated version is ${JSON.stringify(generatedVersion)}, expected ${expectedVersion}`,
    );
  }

  return issues;
}

function checkDocumentation(root, relativePath, expectedVersion) {
  const declaredVersions = [
    ...read(root, relativePath).matchAll(/"gh-aw-version"\s*:\s*"([^"]+)"/g),
  ].map((match) => match[1]);

  return declaredVersions.flatMap((version) => (
    version === expectedVersion
      ? []
      : [`${relativePath}: documented gh-aw-version is ${version}, expected ${expectedVersion}`]
  ));
}

function checkWorkflow(root, relativePath, expectedVersion) {
  const lines = read(root, relativePath).split(/\r?\n/);
  const issues = [];
  const reported = new Set();

  function report(lineIndex, version) {
    if (version === expectedVersion) return;
    const key = `${lineIndex}:${version}`;
    if (reported.has(key)) return;
    reported.add(key);
    issues.push(`${relativePath}:${lineIndex + 1}: gh-aw version is ${version}, expected ${expectedVersion}`);
  }

  for (const [lineIndex, line] of lines.entries()) {
    if (/gh-aw|GH_AW_|compiler_version/.test(line)) {
      for (const match of line.matchAll(/v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?/g)) {
        report(lineIndex, match[0]);
      }
    }

    if (/uses:\s*github\/gh-aw-actions\/setup-cli@/.test(line)) {
      for (let nextIndex = lineIndex + 1; nextIndex < Math.min(lines.length, lineIndex + 9); nextIndex += 1) {
        const version = /^\s+version:\s*["']?(v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)["']?\s*$/.exec(lines[nextIndex])?.[1];
        if (version) {
          report(nextIndex, version);
          break;
        }
      }
    }
  }

  return issues;
}

export function checkGhAwVersionConsistency(root, files = repositoryFiles(root)) {
  const expectedVersion = readCanonicalVersion(root);
  const issues = [];

  for (const relativePath of files) {
    if (path.basename(relativePath) === "aw.yml") {
      issues.push(...checkManifest(root, relativePath, expectedVersion));
      continue;
    }

    const isWorkflowYaml = relativePath.startsWith(WORKFLOW_DIRECTORY)
      && !relativePath.slice(WORKFLOW_DIRECTORY.length).includes("/")
      && relativePath.endsWith(".yml");

    if (
      isWorkflowYaml
      && relativePath.endsWith(LOCK_SUFFIX)
    ) {
      issues.push(...checkLock(root, relativePath, expectedVersion));
      continue;
    }

    if (isWorkflowYaml) {
      issues.push(...checkWorkflow(root, relativePath, expectedVersion));
      continue;
    }

    if (relativePath.startsWith("docs/") && relativePath.endsWith(".md")) {
      issues.push(...checkDocumentation(root, relativePath, expectedVersion));
    }
  }

  return { expectedVersion, issues };
}

function main() {
  const root = path.resolve(import.meta.dirname, "..");
  try {
    const { expectedVersion, issues } = checkGhAwVersionConsistency(root);
    if (issues.length > 0) {
      console.error(`gh-aw version declarations must match ${POLICY_PATH} (${expectedVersion}):`);
      for (const issue of issues) console.error(`- ${issue}`);
      process.exitCode = 1;
      return;
    }
    console.log(`gh-aw version declarations are consistent at ${expectedVersion}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
