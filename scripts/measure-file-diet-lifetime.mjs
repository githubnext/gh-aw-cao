export function originReference(body) {
  assert.equal(typeof body, "string");
  const footers = body.match(/(?:<!--\s*(?:gh-aw-agentic-workflow|agentic-workflow):\s*Daily File Diet\b[\s\S]*?-->|AI generated by \[Daily File Diet\]\([^)]+\))/g) ?? [];
  const references = footers.flatMap(footer => [...footer.matchAll(/https:\/\/github\.com\/([^/\s]+\/[^/\s]+)\/actions\/runs\/([1-9]\d*)/g)]
    .map(match => ({ repository: match[1], runId: match[2] })));
  assert.ok(references.every(ref => aliases.includes(ref.repository)), "Unrecognized producer repository");
  assert.ok(new Set(references.map(ref => ref.runId)).size <= 1, "Conflicting producer runs");
  return references[0] ? { ...references[0], workflowId: "daily-file-diet", attempt: null } : null;
}

export function thresholdContract(source) {
  const lines = source.split("\n").flatMap((text, index) =>
    /\b(?:800|1,?000)\b/.test(text) ? [{ line: index + 1, text }] : []);
  const thresholds = [...new Set(lines.flatMap(item => [...item.text.matchAll(/\b(?:800|1,?000)\b/g)]
    .map(match => Number(match[0].replace(",", "")))))].sort((a, b) => a - b);
  return { sourceSha256: sha256(source), thresholds, lines,
    threshold: thresholds.length === 1 ? thresholds[0] : null };
}

export function monthlyCutoffs(since, end) {
  assert.ok(Date.parse(since) < Date.parse(end));
  const result = [since];
  const date = new Date(since);
  date.setUTCDate(1);
  date.setUTCHours(0, 0, 0, 0);
  date.setUTCMonth(date.getUTCMonth() + 1);
  while (date.getTime() < Date.parse(end)) {
    result.push(date.toISOString().replace(".000Z", "Z"));
    date.setUTCMonth(date.getUTCMonth() + 1);
  }
  return [...result, end];
}

export function acquireHistory(request) {
  const identities = aliases.map(name => request(`repos/${name}`));
  assert.equal(identities[0].id, identities[1].id, "Historical alias is a different repository");
  assert.ok(identities.every(item => item.full_name === repository));
  const history = request(`repos/${repository}/commits?path=${sourcePath}&until=${until}&per_page=100`);
  assert.ok(history.length > 0 && history.length < 100, "Source history requires further pagination");
  const oldest = history.at(-1);
  const introduction = request(`repos/${repository}/commits/${oldest.sha}`);
  assert.ok([sourcePath, sourcePath.replace(/\.md$/, ".lock.yml")].every(file =>
    introduction.files.some(item => item.filename === file && item.status === "added")));
  assert.equal(introduction.parents.length, 1);
  const adoption = { commit: oldest.sha, at: oldest.commit.committer.date,
    baselineCommit: introduction.parents[0].sha };
  const queries = ['"[file-diet]" in:title', '"gh-aw-workflow-id: daily-file-diet" in:body',
    '"gh-aw-tracker-id: daily-file-diet" in:body', '"gh-aw-agentic-workflow: Daily File Diet" in:body',
    '"Daily File Diet" "AI generated by" in:body is:issue'];
  const found = new Map();
  const discovery = queries.map(term => {
    const query = `repo:${repository} ${term} created:${adoption.at.slice(0, 10)}..${until.slice(0, 10)}`;
    let total;
    let count = 0;
    for (let page = 1; page <= 10; page++) {
      const batch = request(`search/issues?q=${encodeURIComponent(query)}&sort=created&order=asc&per_page=100&page=${page}`);
      assert.equal(batch.incomplete_results, false);
      assert.ok(batch.total_count < 1000, "Search result cap prevents complete discovery");
      total ??= batch.total_count;
      assert.equal(batch.total_count, total, "Search population changed while paginating");
      count += batch.items.length;
      for (const item of batch.items) if (Date.parse(item.created_at) >= Date.parse(adoption.at)
        && Date.parse(item.created_at) < Date.parse(until)) found.set(item.number, item);
      if (batch.items.length < 100) break;
    }
    assert.equal(count, total);
    return { query, totalCount: total, complete: true };
  });
  const selected = [...found.values()].filter(item => !item.pull_request
    && (/^\[file-diet\]/i.test(item.title) || (originReference(item.body)
      && /\brefactor\b/i.test(item.title) && /pkg\/[\w./-]+\.go\b/.test(item.body))))
    .sort((a, b) => a.number - b.number);
  assert.ok(selected.length > 0 && selected.length <= 200, "Lifetime issue budget exceeded");
  const observedAt = new Date().toISOString();
  const graphs = new Map();
  for (let offset = 0; offset < selected.length; offset += 10) {
    const data = request("graphql", graphQuery(repository, selected.slice(offset, offset + 10).map(item => item.number)));
    assert.ok(!data.errors?.length, "Issue graph acquisition failed");
    for (const item of selected.slice(offset, offset + 10)) graphs.set(item.number,
      normalizeGraphEntity(data.data.repository[`n${item.number}`], observedAt));
  }
  const timeline = number => {
    const rows = [];
    let complete = false;
    for (let page = 1; page <= 5; page++) {
      const batch = request(`repos/${repository}/issues/${number}/timeline?per_page=100&page=${page}`);
      assert.ok(Array.isArray(batch));
      rows.push(...batch);
      if (batch.length < 100) { complete = true; break; }
    }
    const comments = rows.filter(row => row.event === "commented"
      && /^This issue was automatically closed because it expired on /.test(row.body ?? ""))
      .map(row => ({ type: "expiry-explanation", at: row.created_at, app: row.performed_via_github_app?.slug ?? null,
        bodySha256: sha256(row.body) }));
    return { complete, events: [...projectTimeline(rows.filter(row => row.event !== "commented"), repository), ...comments]
      .filter(event => Date.parse(event.at) < Date.parse(until)) };
  };
  const issues = selected.map(item => {
    const reference = originReference(item.body);
    assert.ok(reference, `Missing named producer footer on #${item.number}`);
    const run = request(`repos/${repository}/actions/runs/${reference.runId}`);
    const validation = run.unavailable ? null : validateRunReference(reference, run, sourcePath, repository);
    const artifacts = run.unavailable ? null
      : request(`repos/${repository}/actions/runs/${reference.runId}/artifacts?per_page=100`);
    if (artifacts) assert.equal(artifacts.total_count, artifacts.artifacts.length, "Truncated artifact inventory");
    return { number: item.number, id: item.node_id, title: item.title, createdAt: item.created_at,
      creatorRole: role(item.user), bodySha256: sha256(item.body),
      targetPath: item.title.match(/pkg\/[\w./-]+\.go\b/)?.[0] ?? item.body.match(/pkg\/[\w./-]+\.go\b/)?.[0] ?? null,
      reference, run: { validation, createdAt: run.created_at ?? null, conclusion: run.conclusion ?? null,
        unavailable: run.unavailable ?? null },
      retainedArtifacts: artifacts ? artifacts.artifacts.map(artifact => ({ id: artifact.id, name: artifact.name,
        expired: artifact.expired, digest: artifact.digest, size: artifact.size_in_bytes })) : null,
      graph: graphs.get(item.number), timeline: timeline(item.number) };
  });
  const related = new Set([...found.values()].filter(item => item.pull_request && /^\[file-diet\]/i.test(item.title))
    .map(item => item.number));
  for (const issue of issues) for (const event of issue.timeline.events) {
    if (event.target?.kind === "pull-request") related.add(event.target.number);
  }
  assert.ok(related.size <= 100, "Related pull-request budget exceeded");
  const pulls = [...related].sort((a, b) => a - b).map(number => {
    const item = request(`repos/${repository}/pulls/${number}`);
    const data = request("graphql", graphQuery(repository, [number]));
    assert.ok(!data.errors?.length);
    const graph = normalizeGraphEntity(data.data.repository[`n${number}`], observedAt);
    const files = [];
    for (let page = 1; page <= 10; page++) {
      const batch = request(`repos/${repository}/pulls/${number}/files?per_page=100&page=${page}`);
      files.push(...batch);
      if (batch.length < 100) break;
    }
    assert.equal(files.length, item.changed_files, "Truncated PR file inventory");
    return { number, id: item.node_id, title: item.title, createdAt: item.created_at, closedAt: item.closed_at,
      mergedAt: item.merged_at, creatorRole: role(item.user), baseSha: item.base.sha, headSha: item.head.sha,
      mergeSha: item.merged_at ? item.merge_commit_sha : null, graph,
      files: files.map(file => ({ path: file.filename, status: file.status, previousPath: file.previous_filename ?? null })) };
  });
  const snapshots = monthlyCutoffs(adoption.at, until).map((at, index) => {
    if (index === 0) return { at, commit: adoption.commit };
    const before = new Date(Date.parse(at) - 1000).toISOString();
    const commits = request(`repos/${repository}/commits?until=${before}&per_page=1`);
    assert.equal(commits.length, 1);
    assert.ok(Date.parse(commits[0].commit.committer.date) < Date.parse(at));
    return { at, commit: commits[0].sha };
  });
  return { schemaVersion: 1, repository, repositoryId: identities[0].id, aliases, sourcePath, adoption, until, observedAt,
    discovery, exclusions: [...found.values()].filter(item => !selected.some(row => row.number === item.number))
      .map(item => ({ number: item.number, title: item.title, kind: item.pull_request ? "pull-request" : "issue" })),
    history: history.map(item => ({ commit: item.sha, at: item.commit.committer.date,
      subject: item.commit.message.split("\n")[0] })), issues, pulls, snapshots };
}

export function collectInventories(proof, git) {
  const measured = [...new Set([proof.adoption.baselineCommit,
    ...proof.snapshots.map(item => item.commit), ...proof.issues.flatMap(item => item.run.validation ? [item.run.validation.headSha] : []),
    ...proof.pulls.filter(item => item.mergeSha).flatMap(item => [item.headSha, item.mergeSha])])];
  git(["fetch", "--quiet", "--depth=1", "--filter=blob:none", "--no-tags", "origin",
    ...new Set([...measured, ...proof.history.map(item => item.commit)])]);
  for (const pull of proof.pulls.filter(item => item.mergeSha)) {
    const headers = git(["cat-file", "-p", pull.mergeSha]).split("\n\n")[0];
    const parents = [...headers.matchAll(/^parent ([a-f0-9]{40})$/gm)].map(match => match[1]);
    assert.ok(parents.length > 0, "Merged PR has no immutable pre-merge parent");
    pull.preMergeSha = parents[0];
  }
  const parents = [...new Set(proof.pulls.flatMap(item => item.preMergeSha ? [item.preMergeSha] : []))];
  if (parents.length) git(["fetch", "--quiet", "--depth=1", "--filter=blob:none", "--no-tags", "origin", ...parents]);
  const revisions = [...new Set([...measured, ...parents])];
  const inventories = Object.fromEntries(revisions.map(commit => [commit, { commit,
    files: git(["ls-tree", "-r", "-z", commit, "--", "pkg"]).split("\0").filter(Boolean).flatMap(entry => {
      const tab = entry.indexOf("\t");
      const [mode, type, blob] = entry.slice(0, tab).split(" ");
      const file = entry.slice(tab + 1);
      return type === "blob" && ["100644", "100755"].includes(mode) && eligiblePath(file)
        ? [{ path: file, blob }] : [];
    }) }]));
  const blobs = [...new Set(Object.values(inventories).flatMap(item => item.files.map(file => file.blob)))];
  assert.ok(blobs.length > 0 && blobs.length <= 50_000, "Lifetime blob budget exceeded");
  const counts = new Map();
  for (let offset = 0; offset < blobs.length; offset += 500) {
    const batch = blobs.slice(offset, offset + 500);
    git(["fetch", "--quiet", "--no-tags", "--no-write-fetch-head", "origin", "--stdin"], { input: `${batch.join("\n")}\n` });
    const bytes = git(["cat-file", "--batch"], { input: `${batch.join("\n")}\n`, encoding: null });
    let cursor = 0;
    for (const blob of batch) {
      const end = bytes.indexOf(10, cursor);
      const [actual, type, size] = bytes.subarray(cursor, end).toString().split(" ");
      assert.equal(actual, blob);
      assert.equal(type, "blob");
      const content = bytes.subarray(end + 1, end + 1 + Number(size));
      assert.equal(createHash("sha1").update(`blob ${content.length}\0`).update(content).digest("hex"), blob);
      const lines = newlineCount(content);
      assert.equal(lines, Number(execFileSync("wc", ["-l"], { input: content, encoding: "utf8" }).trim()));
      counts.set(blob, { lines, bytes: content.length });
      cursor = end + 1 + Number(size) + 1;
    }
    assert.equal(cursor, bytes.length);
  }
  for (const inventory of Object.values(inventories)) {
    inventory.files = inventory.files.map(file => ({ ...file, ...counts.get(file.blob) }));
    inventory.inventoryDigest = censusDigest(inventory.files);
  }
  proof.contracts = proof.history.map(item => ({ ...item, ...thresholdContract(git(["show", `${item.commit}:${sourcePath}`])) }));
  proof.producerContracts = Object.fromEntries([...new Set(proof.issues.flatMap(item => item.run.validation ? [item.run.validation.headSha] : []))]
    .map(commit => [commit, thresholdContract(git(["show", `${commit}:${sourcePath}`]))]));
  return { inventories, uniqueBlobs: blobs.length };
}

export function acquireExecutions(proof, request) {
  const runs = [];
  for (let index = 1; index < proof.snapshots.length; index++) {
    const start = proof.snapshots[index - 1].at;
    const end = proof.snapshots[index].at;
    const before = new Date(Date.parse(end) - 1000).toISOString();
    const created = encodeURIComponent(`${start}..${before}`);
    let total;
    let count = 0;
    for (let page = 1; page <= 10; page++) {
      const batch = request(`repos/${repository}/actions/workflows/daily-file-diet.lock.yml/runs?created=${created}&per_page=100&page=${page}`);
      assert.ok(batch.total_count < 1000, "Monthly run search exceeds the API result cap");
      total ??= batch.total_count;
      assert.equal(batch.total_count, total);
      count += batch.workflow_runs.length;
      for (const item of batch.workflow_runs) {
        assert.equal(String(item.path).split("@")[0], sourcePath.replace(/\.md$/, ".lock.yml"));
        assert.equal(item.repository.id, proof.repositoryId);
        assert.ok(Date.parse(item.created_at) >= Date.parse(start) && Date.parse(item.created_at) < Date.parse(end));
        runs.push({ id: String(item.id), at: item.created_at, headSha: item.head_sha,
          event: item.event, status: item.status, conclusion: item.conclusion });
      }
      if (batch.workflow_runs.length < 100) break;
    }
    assert.equal(count, total, "Incomplete retained-run pagination");
  }
  assert.equal(new Set(runs.map(run => run.id)).size, runs.length);
  return { observedAt: new Date().toISOString(), completeRetainedEnumeration: true,
    completeHistoricalExecutions: false,
    missingReferencedRunIds: [...new Set(proof.issues.map(issue => issue.reference.runId))]
      .filter(id => !runs.some(run => run.id === id)), runs,
    limitation: "Deleted runs cannot be reconstructed from this endpoint. Success is not evidence of inspection, safe-output execution or accepted value." };
}

export function verifyCreationReceipt(issue) {
  const receipt = issue.receipt;
  if (receipt?.status !== "available") return false;
  assert.equal(String(receipt.runId), issue.reference.runId);
  assert.equal(receipt.headSha, issue.run.validation?.headSha);
  assert.equal(sha256(receipt.content), receipt.entrySha256);
  assert.equal(`sha256:${receipt.archiveSha256}`, receipt.digest);
  const rows = receipt.content.trim().split("\n").map(line => JSON.parse(line));
  assert.equal(rows.length, 1, "Unrecognized multi-output creation receipt");
  const item = rows[0];
  assert.equal(item.type, "create_issue");
  assert.equal(item.number, issue.number);
  if (Object.hasOwn(item, "metadata")) assert.equal(item.metadata.node_id, issue.id);
  assert.ok(aliases.includes(item.repo));
  assert.equal(item.url, `https://github.com/${item.repo}/issues/${issue.number}`);
  return true;
}

function collectCreationReceipts(proof, request) {
  for (const issue of proof.issues) {
    const artifact = issue.retainedArtifacts?.find(item => item.name === "safe-outputs-items" && !item.expired);
    issue.receipt = { status: "missing", reason: issue.run.unavailable
      ? "Producer run unavailable" : "No retained safe-output creation artifact" };
    if (!artifact) continue;
    const metadata = request(`repos/${repository}/actions/artifacts/${artifact.id}`);
    assert.ok(metadata.size_in_bytes < 2 * 1024 * 1024);
    assert.equal(metadata.digest, artifact.digest);
    assert.equal(String(metadata.workflow_run.id), issue.reference.runId);
    assert.equal(metadata.workflow_run.head_sha, issue.run.validation.headSha);
    const bytes = request(`repos/${repository}/actions/artifacts/${artifact.id}/zip`, null, true);
    assert.equal(`sha256:${sha256(bytes)}`, metadata.digest);
    const temporary = mkdtempSync(path.join(os.tmpdir(), "file-diet-lifetime-receipt-"));
    try {
      const zip = path.join(temporary, "receipt.zip");
      writeFileSync(zip, bytes);
      const content = execFileSync("unzip", ["-p", zip, "safe-output-items.jsonl"],
        { encoding: "utf8", maxBuffer: 64 * 1024 });
      issue.receipt = { status: "available", runId: metadata.workflow_run.id, headSha: metadata.workflow_run.head_sha,
        artifactId: artifact.id, digest: metadata.digest, archiveSha256: sha256(bytes),
        entrySha256: sha256(content), observedAt: new Date().toISOString(), content };
      verifyCreationReceipt(issue);
    } finally {
      rmSync(temporary, { recursive: true, force: true });
    }
  }
}

export function evaluateLifetime(proof, inventories) {
  const inventory = commit => {
    const item = inventories[commit];
    assert.ok(item && item.inventoryDigest === censusDigest(item.files), "Missing or corrupt inventory");
    assert.equal(new Set(item.files.map(file => file.path)).size, item.files.length);
    assert.ok(item.files.every(file => eligiblePath(file.path) && Number.isSafeInteger(file.lines) && file.lines >= 0));
    return item.files;
  };
  const lineCount = (commit, target) => inventory(commit).find(file => file.path === target)?.lines ?? null;
  const distinct = rows => [...new Set(rows)];
  const issueEvaluations = proof.issues.map(issue => {
    const commit = issue.run?.validation?.headSha;
    const contract = commit ? proof.producerContracts?.[commit] : null;
    const files = commit ? inventory(commit) : null;
    const targetLines = files?.find(file => file.path === issue.targetPath)?.lines ?? null;
    const largestLines = files ? Math.max(...files.map(file => file.lines)) : null;
    return { number: issue.number, targetPath: issue.targetPath, creatorVerified: verifyCreationReceipt(issue),
      threshold: contract?.threshold ?? null, targetLines, largestLines,
      correctAtSourceThreshold: files && contract?.threshold ? targetLines !== null
        && targetLines >= contract.threshold && targetLines === largestLines : null };
  });
  const deliveries = proof.pulls.filter(pull => pull.mergedAt && Date.parse(pull.mergedAt) < Date.parse(proof.until))
    .map(pull => {
      const linked = proof.issues.filter(issue => Date.parse(issue.createdAt) <= Date.parse(pull.createdAt)
        && (pull.graph.edges.some(edge => edge.relation === "declares-closing" && edge.target.id === issue.id)
          || issue.timeline.events.filter(event => ["connected", "disconnected"].includes(event.type)
            && event.target?.kind === "pull-request" && event.target.number === pull.number
            && Date.parse(event.at) <= Date.parse(pull.mergedAt))
            .sort((left, right) => Date.parse(left.at) - Date.parse(right.at)).at(-1)?.type === "connected"));
      return { number: pull.number, mergedAt: pull.mergedAt, creatorRole: pull.creatorRole,
        issues: linked.map(issue => issue.number), historyComplete: pull.graph.closingLinksComplete,
        receiptVerifiedIssues: linked.filter(verifyCreationReceipt).map(issue => issue.number),
        oversized800Reduction: inventory(pull.preMergeSha).filter(file => file.lines >= 800).length
          - inventory(pull.mergeSha).filter(file => file.lines >= 800).length,
        oversized1000Reduction: inventory(pull.preMergeSha).filter(file => file.lines >= 1000).length
          - inventory(pull.mergeSha).filter(file => file.lines >= 1000).length,
        targets: distinct(linked.map(issue => issue.targetPath).filter(Boolean)).map(target => {
          const before = lineCount(pull.preMergeSha, target);
          const after = lineCount(pull.mergeSha, target);
          const newFiles = pull.files.filter(file => ["added", "renamed"].includes(file.status) && eligiblePath(file.path))
            .map(file => ({ path: file.path, lines: lineCount(pull.mergeSha, file.path) }));
          return { path: target, before, after,
            creatorVerified: linked.some(issue => issue.targetPath === target && verifyCreationReceipt(issue)),
            resolved800: before !== null && before >= 800 && (after === null || after < 800),
            resolved1000: before !== null && before >= 1000 && (after === null || after < 1000), newFiles,
            newFilesUnder500: newFiles.length > 0 && newFiles.every(file => file.lines !== null && file.lines < 500) };
        }),
        acceptedBehaviorPreserving: null };
    });
  const periods = proof.snapshots.map((snapshot, index) => {
    const files = inventory(snapshot.commit);
    const start = index ? proof.snapshots[index - 1].at : snapshot.at;
    const inside = at => Date.parse(at) >= Date.parse(start) && Date.parse(at) < Date.parse(snapshot.at);
    const issues = proof.issues.filter(issue => inside(issue.createdAt));
    const merged = deliveries.filter(pull => inside(pull.mergedAt));
    const runs = proof.executions?.runs.filter(run => inside(run.at));
    return { start, end: snapshot.at, commit: snapshot.commit, eligibleFiles: files.length,
      oversized800: scoreMetric("oversized", { valid: true, coverageStatus: "complete",
        eligibleCount: files.length, lineCounts: files.map(file => file.lines) }),
      oversized1000: files.filter(file => file.lines >= 1000).length,
      issues: issues.length, distinctReportedTargets: distinct(issues.map(issue => issue.targetPath).filter(Boolean)).length,
      mergedLinkedPulls: merged.filter(pull => pull.issues.length).map(pull => pull.number),
      linkedNetOversized800Reduction: merged.filter(pull => pull.issues.length)
        .reduce((sum, pull) => sum + pull.oversized800Reduction, 0),
      retainedRuns: runs?.length ?? null,
      retainedRunConclusions: runs ? Object.fromEntries(distinct(runs.map(run => run.conclusion ?? "pending"))
        .map(conclusion => [conclusion, runs.filter(run => (run.conclusion ?? "pending") === conclusion).length])) : null,
      resolved800: merged.flatMap(pull => pull.targets.filter(target => target.resolved800)
        .map(target => ({ pull: pull.number, path: target.path }))),
      acceptedBehaviorPreserving: null };
  });
  return { adoption: proof.adoption, until: proof.until, periods, deliveries, issueEvaluations,
    totals: { issues: proof.issues.length, distinctReportedTargets: distinct(proof.issues.map(issue => issue.targetPath).filter(Boolean)).length,
      relatedPulls: proof.pulls.length, mergedRelatedPulls: deliveries.length,
      mergedExplicitlyLinkedPulls: deliveries.filter(pull => pull.issues.length).length,
      resolved800: deliveries.flatMap(pull => pull.targets.filter(target => target.resolved800)).length,
      receiptLinkedMergedPulls: deliveries.filter(pull => pull.receiptVerifiedIssues.length).length,
      receiptLinkedResolved800: deliveries.flatMap(pull => pull.targets.filter(target => target.creatorVerified && target.resolved800)).length,
      linkedNetOversized800Reduction: deliveries.filter(pull => pull.issues.length)
        .reduce((sum, pull) => sum + pull.oversized800Reduction, 0),
      verifiedCreationReceipts: issueEvaluations.filter(issue => issue.creatorVerified).length,
      verifiedCorrectReports: issueEvaluations.filter(issue => issue.creatorVerified && issue.correctAtSourceThreshold).length,
      verifiedProducerRuns: proof.issues.filter(issue => issue.run?.validation).length,
      automaticExpiryExplanations: proof.issues.filter(issue => issue.timeline.events.some(event =>
        event.type === "expiry-explanation" && event.app === "github-actions")).length,
      completeIssueTimelines: proof.issues.filter(issue => issue.timeline.complete).length,
      retainedRuns: proof.executions?.runs.length ?? null,
      lifetimeRunCount: null,
      acceptedBehaviorPreserving: null } };
}

export function readLifetime(directory) {
  const proof = readCensusJson(path.join(directory, "proof.json.gz"));
  assert.equal(proof.schemaVersion, 1);
  assert.equal(proof.repository, repository);
  assert.equal(proof.sourcePath, sourcePath);
  assert.deepEqual(proof.aliases, aliases);
  assert.deepEqual(proof.snapshots.map(item => item.at), monthlyCutoffs(proof.adoption.at, proof.until));
  assert.equal(new Set(proof.issues.map(issue => issue.id)).size, proof.issues.length);
  assert.equal(new Set(proof.pulls.map(pull => pull.id)).size, proof.pulls.length);
  const inventories = Object.fromEntries(proof.inventoryPartitions.map(part => {
    assert.equal(part.file, path.basename(part.file));
    assert.match(part.file, /^inventory-[a-f0-9]{40}\.json\.gz$/);
    const inventory = readCensusJson(path.join(directory, part.file));
    assert.equal(censusDigest(inventory), part.sha256, "Inventory partition digest mismatch");
    assert.equal(inventory.commit, part.commit);
    assert.equal(inventory.inventoryDigest, censusDigest(inventory.files));
    assert.ok(inventory.files.every(file => eligiblePath(file.path) && /^[a-f0-9]{40}$/.test(file.blob)
      && Number.isSafeInteger(file.lines) && file.lines >= 0 && Number.isSafeInteger(file.bytes) && file.bytes >= file.lines));
    return [part.commit, inventory];
  }));
  assert.equal(Object.keys(inventories).length, proof.inventoryPartitions.length);
  const blobs = new Map();
  for (const item of Object.values(inventories)) for (const file of item.files) {
    const count = [file.lines, file.bytes];
    if (blobs.has(file.blob)) assert.deepEqual(blobs.get(file.blob), count);
    else blobs.set(file.blob, count);
  }
  assert.equal(blobs.size, proof.uniqueBlobs);
  return { proof, inventories };
}

function requestWithCache(directory) {
  mkdirSync(directory, { recursive: true });
  let requests = 0;
  return (endpoint, query, binary = false) => {
    assert.ok(++requests <= 1000, "Lifetime API request budget exceeded");
    const cache = path.join(directory, `${sha256(JSON.stringify(binary ? [endpoint, query ?? null, "binary"]
      : [endpoint, query ?? null]))}${binary ? ".zip" : ".json.gz"}`);
    if (existsSync(cache)) return binary ? readFileSync(cache) : readCensusJson(cache);
    const args = query ? ["api", "graphql", "-f", `query=${query}`] : ["api", endpoint];
    let value;
    try {
      const result = execFileSync("gh", args, { encoding: binary ? null : "utf8", timeout: 60_000,
        maxBuffer: 16 * 1024 * 1024, stdio: ["pipe", "pipe", "pipe"] });
      value = binary ? result : JSON.parse(result);
    } catch (error) {
      if (!query && /^repos\/github\/gh-aw\/actions\/runs\/\d+$/.test(endpoint)
        && /\(HTTP 404\)/.test(error.stderr ?? "")) {
        value = { unavailable: { status: 404, endpoint, reason: "Producer run is no longer available" } };
        console.warn(JSON.stringify(value));
      } else {
        throw error;
      }
    }
    if (binary) writeFileSync(cache, value);
    else writeCensusJson(cache, value);
    return value;
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, file, destination, cache, ...extra] = process.argv.slice(2);
  assert.ok(["--acquire", "--inventories", "--runs", "--replay"].includes(mode) && file && destination && !extra.length
    && (mode === "--inventories" ? Boolean(cache) : !cache),
  "usage: measure-file-diet-lifetime.mjs --acquire NEW.json.gz CACHE_DIR | --inventories API.json.gz NEW_DIR CACHE_DIR | --runs PROOF_DIR CACHE_DIR | --replay PROOF_DIR REPORT.json");
  if (mode === "--acquire") {
    assert.ok(!existsSync(file), "Refusing to replace a lifetime acquisition");
    writeCensusJson(file, acquireHistory(requestWithCache(destination)));
  } else if (mode === "--inventories") {
    assert.ok(!existsSync(destination), "Refusing to replace lifetime inventories");
    const proof = readCensusJson(file);
    collectCreationReceipts(proof, requestWithCache(cache));
    const temporary = mkdtempSync(path.join(os.tmpdir(), "file-diet-lifetime-"));
    const git = (args, options = {}) => execFileSync("git", ["--git-dir", temporary, ...args],
      { encoding: "utf8", timeout: 240_000, maxBuffer: 128 * 1024 * 1024, ...options });
    try {
      git(["init", "--bare", "--quiet"]);
      git(["remote", "add", "origin", `https://github.com/${repository}.git`]);
      git(["config", "remote.origin.promisor", "true"]);
      git(["config", "remote.origin.partialclonefilter", "blob:none"]);
      const { inventories, uniqueBlobs } = collectInventories(proof, git);
      mkdirSync(destination, { recursive: true });
      proof.inventoryPartitions = Object.values(inventories).map(item => {
        const name = `inventory-${item.commit}.json.gz`;
        writeCensusJson(path.join(destination, name), item);
        return { file: name, commit: item.commit, sha256: censusDigest(item) };
      });
      proof.uniqueBlobs = uniqueBlobs;
      proof.instrumentSha256 = sha256(readFileSync(fileURLToPath(import.meta.url)));
      writeCensusJson(path.join(destination, "proof.json.gz"), proof);
      console.log(JSON.stringify(evaluateLifetime(proof, inventories).totals));
    } finally {
      rmSync(temporary, { recursive: true, force: true });
    }
  } else if (mode === "--runs") {
    const index = path.join(file, "proof.json.gz");
    const proof = readCensusJson(index);
    assert.ok(!proof.executions, "Refusing to replace retained execution evidence");
    proof.executions = acquireExecutions(proof, requestWithCache(destination));
    proof.executionInstrumentSha256 = sha256(readFileSync(fileURLToPath(import.meta.url)));
    writeCensusJson(index, proof);
  } else {
    const { proof, inventories } = readLifetime(file);
    writeFileSync(destination, `${JSON.stringify(evaluateLifetime(proof, inventories), null, 2)}\n`);
  }
}
