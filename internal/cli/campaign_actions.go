package cli

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	ghAwActionPattern = regexp.MustCompile(`(uses:\s*github/gh-aw-actions/(?:setup-cli|setup))@([^\s#]+)([^\r\n]*)`)
	setupPinPattern   = regexp.MustCompile(`(?i)github/gh-aw-actions/setup-cli@([0-9a-f]{40})\s*#\s*([^\s]+)`)
)

func pinAutoUpgradeActions() error {
	workflow, err := repositoryPath(filepath.Join(".github", "workflows", "agentic-auto-upgrade.yml"))
	if err != nil {
		return err
	}
	content, err := os.ReadFile(workflow)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	source := string(content)
	var version string
	for _, match := range ghAwActionPattern.FindAllStringSubmatch(source, -1) {
		if commitPattern.MatchString(match[2]) {
			continue
		}
		if version != "" && version != match[2] {
			return fmt.Errorf("agentic-auto-upgrade.yml contains inconsistent mutable gh-aw Action revisions")
		}
		version = match[2]
	}
	if version == "" {
		return nil
	}
	if !strings.HasPrefix(source, "# This file was automatically generated by pkg/workflow/auto_update_workflow.go") {
		return fmt.Errorf("agentic-auto-upgrade.yml contains mutable gh-aw Action references but is not a recognized generated workflow")
	}
	setup, err := repositoryPath(filepath.Join(".github", "actions", "setup-gh-aw", "action.yml"))
	if err != nil {
		return err
	}
	action, err := os.ReadFile(setup)
	if err != nil {
		return err
	}
	match := setupPinPattern.FindStringSubmatch(string(action))
	if match == nil || match[2] != version {
		return fmt.Errorf("unable to resolve the immutable github/gh-aw-actions revision for %s from .github/actions/setup-gh-aw/action.yml", version)
	}
	revision := strings.ToLower(match[1])
	pinned := ghAwActionPattern.ReplaceAllStringFunc(source, func(line string) string {
		match := ghAwActionPattern.FindStringSubmatch(line)
		if commitPattern.MatchString(match[2]) {
			return line
		}
		suffix := match[3]
		if strings.TrimSpace(suffix) == "" {
			suffix = " # " + match[2]
		}
		return match[1] + "@" + revision + suffix
	})
	return os.WriteFile(workflow, []byte(pinned), 0o644)
}
