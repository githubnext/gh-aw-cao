package cli

import (
	"os"
	"strings"
	"testing"
)

func TestPinGeneratedAutoUpgradeActions(t *testing.T) {
	t.Chdir(t.TempDir())
	writeTestFile(t, ".github/actions/setup-gh-aw/action.yml",
		"uses: github/gh-aw-actions/setup-cli@"+strings.ToUpper(testCampaignSHA)+" # v0.92.4\n")
	original := "# This file was automatically generated by pkg/workflow/auto_update_workflow.go\n" +
		"uses: github/gh-aw-actions/setup-cli@v0.92.4\n" +
		"uses: github/gh-aw-actions/setup@v0.92.4 # keep this comment\n" +
		"uses: github/gh-aw-actions/setup-cli@" + strings.Repeat("a", 40) + "\n"
	file := ".github/workflows/agentic-auto-upgrade.yml"
	writeTestFile(t, file, original)
	if err := pinAutoUpgradeActions(); err != nil {
		t.Fatal(err)
	}
	content, err := os.ReadFile(file)
	want := strings.ReplaceAll(original, "setup-cli@v0.92.4", "setup-cli@"+testCampaignSHA+" # v0.92.4")
	want = strings.ReplaceAll(want, "setup@v0.92.4", "setup@"+testCampaignSHA)
	if err != nil || string(content) != want {
		t.Fatalf("pinned workflow = %q, want %q: %v", content, want, err)
	}
	if err := pinAutoUpgradeActions(); err != nil {
		t.Fatal(err)
	}
}

func TestPinAutoUpgradeActionsFailsClosed(t *testing.T) {
	for _, tt := range []struct{ name, source, setup string }{
		{"custom workflow", "uses: github/gh-aw-actions/setup@v1\n", testCampaignSHA + " # v1"},
		{"inconsistent versions", "# This file was automatically generated by pkg/workflow/auto_update_workflow.go\nuses: github/gh-aw-actions/setup@v1\nuses: github/gh-aw-actions/setup-cli@v2\n", testCampaignSHA + " # v1"},
		{"mismatched pin", "# This file was automatically generated by pkg/workflow/auto_update_workflow.go\nuses: github/gh-aw-actions/setup@v1\n", testCampaignSHA + " # v2"},
		{"no pin", "# This file was automatically generated by pkg/workflow/auto_update_workflow.go\nuses: github/gh-aw-actions/setup@v1\n", "v1"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Chdir(t.TempDir())
			file := ".github/workflows/agentic-auto-upgrade.yml"
			writeTestFile(t, file, tt.source)
			writeTestFile(t, ".github/actions/setup-gh-aw/action.yml", "uses: github/gh-aw-actions/setup-cli@"+tt.setup+"\n")
			if err := pinAutoUpgradeActions(); err == nil {
				t.Fatal("expected pinning error")
			}
			if content, err := os.ReadFile(file); err != nil || string(content) != tt.source {
				t.Fatalf("workflow changed on failed pinning: %q %v", content, err)
			}
		})
	}
	t.Run("missing workflow", func(t *testing.T) {
		t.Chdir(t.TempDir())
		if err := pinAutoUpgradeActions(); err != nil {
			t.Fatal(err)
		}
	})
}
